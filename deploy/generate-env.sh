#!/usr/bin/env bash
#
# Generate deploy/.env with strong secrets for the production stack.
#
#   ./deploy/generate-env.sh            # interactive (prompts for admin creds)
#   ./deploy/generate-env.sh --force    # overwrite an existing deploy/.env
#
# Security notes:
#   - Refuses to overwrite an existing deploy/.env unless --force is given.
#   - Writes the file with mode 600 and a umask of 077 (no world-readable window).
#   - Never prints generated secret VALUES except when it must create an admin
#     password for you, in which case it prints them once with a clear banner.
#   - Literal "$" in the bcrypt hash is escaped as "$$" for Docker Compose.

set -euo pipefail

umask 077

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$ROOT/deploy/.env"
FORCE=0

for arg in "$@"; do
  case "$arg" in
    --force) FORCE=1 ;;
    -h|--help) sed -n '2,16p' "$0"; exit 0 ;;
    *) echo "Unknown argument: $arg" >&2; exit 2 ;;
  esac
done

if [[ -f "$ENV_FILE" && $FORCE -ne 1 ]]; then
  echo "Refusing to overwrite existing $ENV_FILE (use --force to replace)." >&2
  exit 1
fi

need() { command -v "$1" >/dev/null 2>&1 || { echo "Missing required tool: $1" >&2; exit 1; }; }
need openssl

rand_hex() { openssl rand -hex "$1"; }

# --- bcrypt hashing (Node-RED admin password) ---------------------------------
bcrypt_hash() {
  local password="$1"
  if command -v htpasswd >/dev/null 2>&1; then
    # apache2-utils: -B bcrypt, -C 10 cost, "" empty username, strip "user:"
    htpasswd -bnBC 10 "" "$password" | tr -d ':\n'
  elif command -v python3 >/dev/null 2>&1 && python3 -c 'import bcrypt' >/dev/null 2>&1; then
    python3 - "$password" <<'PY'
import bcrypt, sys
print(bcrypt.hashpw(sys.argv[1].encode(), bcrypt.gensalt(rounds=10)).decode())
PY
  else
    echo "ERROR: need either 'htpasswd' (apache2-utils) or python3 with the" >&2
    echo "       'bcrypt' module to hash the Node-RED password." >&2
    echo "       Install one of them and re-run." >&2
    exit 1
  fi
}

prompt_secret() {
  local label="$1" minlen="$2" value=""
  if [[ -t 0 ]]; then
    while true; do
      read -r -s -p "$label (min ${minlen} chars): " value; echo
      if [[ ${#value} -ge $minlen ]]; then
        printf '%s' "$value"
        return
      fi
      echo "Too short, try again." >&2
    done
  else
    # Non-interactive: generate a strong value and tell the operator once.
    value="$(rand_hex 16)" # 32 hex chars
    echo "Generated $label: $value" >&2
    printf '%s' "$value"
  fi
}

echo "Generating $ENV_FILE ..."

POSTGRES_PASSWORD="$(rand_hex 24)"
JWT_SECRET="$(rand_hex 48)"
JWT_REFRESH_SECRET="$(rand_hex 48)"
INGEST_API_KEY="$(rand_hex 32)"
GRAFANA_ADMIN_PASSWORD="$(rand_hex 16)"
NODE_RED_CREDENTIAL_SECRET="$(rand_hex 32)"

SEED_ADMIN_PASSWORD="$(prompt_secret 'Backend seed admin password' 12)"
NODERED_ADMIN_PASSWORD="$(prompt_secret 'Node-RED editor password' 8)"
NODERED_HASH="$(bcrypt_hash "$NODERED_ADMIN_PASSWORD")"
# Escape "$" -> "$$" for Docker Compose env-file interpolation.
NODERED_HASH_ESCAPED="${NODERED_HASH//\$/\$\$}"

read -r -p "Public hostname (e.g. iot.example.com): " PUBLIC_HOSTNAME
PUBLIC_HOSTNAME="${PUBLIC_HOSTNAME:-<PUBLIC_HOSTNAME>}"

TAILSCALE_IP=""
if command -v tailscale >/dev/null 2>&1; then
  TAILSCALE_IP="$(tailscale ip -4 2>/dev/null | head -n1 || true)"
fi
if [[ -z "$TAILSCALE_IP" ]]; then
  read -r -p "Tailscale IP (100.x.y.z): " TAILSCALE_IP
fi

cat > "$ENV_FILE" <<EOF
# GENERATED by deploy/generate-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) -- KEEP SECRET.
PUBLIC_ORIGIN=https://${PUBLIC_HOSTNAME}
TAILSCALE_IP=${TAILSCALE_IP}
IMAGE_TAG=latest
FRONTEND_PORT=5173

POSTGRES_DB=iot_monitoring
POSTGRES_USER=iot_user
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
POSTGRES_PORT=5432

JWT_SECRET=${JWT_SECRET}
JWT_REFRESH_SECRET=${JWT_REFRESH_SECRET}
JWT_EXPIRES_IN=15m
JWT_REFRESH_EXPIRES_IN=7d
LOG_LEVEL=info

SEED_ADMIN_EMAIL=admin@${PUBLIC_HOSTNAME}
SEED_ADMIN_PASSWORD=${SEED_ADMIN_PASSWORD}
INGEST_API_KEY=${INGEST_API_KEY}

RETENTION_MAX_SIZE_GB=5
RETENTION_CHECK_INTERVAL_MINUTES=15
RETENTION_BYTES_PER_ROW=240

CORS_ORIGIN=https://${PUBLIC_HOSTNAME}

GRAFANA_ADMIN_USER=admin
GRAFANA_ADMIN_PASSWORD=${GRAFANA_ADMIN_PASSWORD}

NODE_RED_ADMIN_USER=admin
NODE_RED_ADMIN_PASSWORD_HASH=${NODERED_HASH_ESCAPED}
NODE_RED_CREDENTIAL_SECRET=${NODE_RED_CREDENTIAL_SECRET}
NODE_RED_DISABLE_EDITOR=false

TZ=$(readlink /etc/localtime 2>/dev/null | sed 's#.*/zoneinfo/##' || echo UTC)
EOF

chmod 600 "$ENV_FILE"

echo
echo "Wrote $ENV_FILE (mode 600)."
echo "NOT stored anywhere else - record these two now:"
echo "  Backend seed admin password : ${SEED_ADMIN_PASSWORD}"
echo "  Node-RED editor password    : ${NODERED_ADMIN_PASSWORD}"
echo
echo "Next: verify with"
echo "  docker compose --env-file deploy/.env -f compose.yaml -f compose.production.yaml config -q"
